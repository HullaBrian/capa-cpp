#!/usr/bin/env python3
"""
Regenerate capa-core/src/com_database.cpp from capa's COM database.

capa expands a rule feature like `com/class: InternetExplorer` into the GUIDs that name
that class or interface (capa.rules.translate_com_feature), looked up in
capa/features/com/{classes,interfaces}.py. That data is ~2 MB of Python, so it is
embedded here zlib-compressed and base64-encoded, and inflated on first use.

usage:
    pip install flare-capa            # the version whose database you want
    python scripts/gen_com_database.py
"""

import base64
import zlib
from pathlib import Path

import capa.version
import capa.features.com as com
from capa.features.com import ComType

OUT = Path(__file__).resolve().parent.parent / "capa-core" / "src" / "com_database.cpp"
CHUNK = 16000  # MSVC limits a single string literal to 16380 bytes


def encode(com_type: ComType) -> list[str]:
    db = com.load_com_database(com_type)
    text = "".join(f"{name}\t{','.join(guids)}\n" for name, guids in db.items())
    blob = base64.b64encode(zlib.compress(text.encode("utf-8"), 9)).decode("ascii")
    return [blob[i : i + CHUNK] for i in range(0, len(blob), CHUNK)]


def emit_array(name: str, chunks: list[str]) -> str:
    lines = [f"const char* const {name}[] = {{"]
    lines += [f'    "{c}",' for c in chunks]
    lines += ["};"]
    return "\n".join(lines)


def main():
    classes = encode(ComType.CLASS)
    interfaces = encode(ComType.INTERFACE)
    OUT.write_text(
        "// GENERATED by scripts/gen_com_database.py from capa "
        + capa.version.__version__
        + " -- do not edit.\n"
        "//\n"
        "// capa/features/com/{classes,interfaces}.py as `name<TAB>guid,guid...` lines,\n"
        "// zlib-compressed and base64-encoded. See com_database.h.\n"
        '#include "com_database.h"\n'
        "\n"
        "namespace capa::com_data {\n"
        "\n" + emit_array("kClasses", classes) + "\n"
        f"const std::size_t kClassesCount = {len(classes)};\n"
        "\n" + emit_array("kInterfaces", interfaces) + "\n"
        f"const std::size_t kInterfacesCount = {len(interfaces)};\n"
        "\n"
        "}  // namespace capa::com_data\n",
        encoding="ascii",
        newline="\n",
    )
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
